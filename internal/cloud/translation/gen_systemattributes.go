//go:build ignore

// This program writes systemattributes_gen.go from the search attribute
// definitions of a Temporal Server release. It imports the server module, so it
// is excluded from the build and run by `mise run gen:search-attributes` in a
// throwaway module pinned to the chosen release.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"os"
	"runtime/debug"
	"slices"

	enumspb "go.temporal.io/api/enums/v1"
	"go.temporal.io/server/common/searchattribute/sadefs"
)

const serverModule = "go.temporal.io/server"

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen_systemattributes <output file>")
		os.Exit(2)
	}

	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(out string) error {
	version, err := serverVersion()
	if err != nil {
		return err
	}

	// OSS ListSearchAttributes reports both sets as system attributes.
	attrs := sadefs.System()
	maps.Copy(attrs, sadefs.Predefined())

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by `mise run gen:search-attributes`. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package translation\n\n")
	fmt.Fprintf(&buf, "import enumspb \"go.temporal.io/api/enums/v1\"\n\n")
	fmt.Fprintf(&buf, "// systemAttributes are the system and predefined search attributes of\n")
	fmt.Fprintf(&buf, "// %s %s.\n", serverModule, version)
	fmt.Fprintf(&buf, "var systemAttributes = map[string]enumspb.IndexedValueType{\n")

	for _, name := range slices.Sorted(maps.Keys(attrs)) {
		typ, ok := enumspb.IndexedValueType_name[int32(attrs[name])]
		if !ok || attrs[name] == enumspb.INDEXED_VALUE_TYPE_UNSPECIFIED {
			return fmt.Errorf("search attribute %q has unknown type %d", name, attrs[name])
		}

		fmt.Fprintf(&buf, "%q: enumspb.%s,\n", name, typ)
	}

	fmt.Fprintf(&buf, "}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}

	return os.WriteFile(out, src, 0o644)
}

// serverVersion reports the server release this binary was built against.
func serverVersion() (string, error) {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return "", fmt.Errorf("no build info")
	}

	for _, dep := range info.Deps {
		if dep.Path == serverModule {
			return dep.Version, nil
		}
	}

	return "", fmt.Errorf("%s is not a dependency", serverModule)
}
